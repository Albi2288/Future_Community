-- 1) Zeitpunkt der letzten Aktivität am Profil speichern.
ALTER TABLE public.profiles
  ADD COLUMN IF NOT EXISTS last_seen_at timestamptz;

-- 2) Sichere RPC: Ein angemeldeter Benutzer kann nur seine eigene Online-Zeit aktualisieren.
CREATE OR REPLACE FUNCTION public.touch_last_seen()
RETURNS timestamptz
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth
AS $$
DECLARE v_stamp timestamptz := now();
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'Nicht angemeldet';
  END IF;
  UPDATE public.profiles
     SET last_seen_at = v_stamp
   WHERE id = auth.uid();
  RETURN v_stamp;
END;
$$;
REVOKE ALL ON FUNCTION public.touch_last_seen() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.touch_last_seen() TO authenticated;

-- 3) Audit-Tabelle: nur Name/Username und Löschzeitpunkt, keine privaten Profildaten.
CREATE TABLE IF NOT EXISTS public.deleted_profiles_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username text,
  display_name text,
  deleted_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.deleted_profiles_audit ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Chef admin can read deleted profile names" ON public.deleted_profiles_audit;
CREATE POLICY "Chef admin can read deleted profile names"
ON public.deleted_profiles_audit
FOR SELECT TO authenticated
USING (
  EXISTS (
    SELECT 1 FROM public.profiles p
    WHERE p.id = auth.uid() AND p.is_admin_chef = true
  )
);
GRANT SELECT ON public.deleted_profiles_audit TO authenticated;

-- 4) Vor dem Löschen eines Profils den Namen sichern.
CREATE OR REPLACE FUNCTION public.audit_deleted_profile_name()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  INSERT INTO public.deleted_profiles_audit (username, display_name, deleted_at)
  VALUES (OLD.username, OLD.display_name, now());
  RETURN OLD;
END;
$$;

DROP TRIGGER IF EXISTS profiles_audit_deleted_name ON public.profiles;
CREATE TRIGGER profiles_audit_deleted_name
BEFORE DELETE ON public.profiles
FOR EACH ROW
EXECUTE FUNCTION public.audit_deleted_profile_name();

