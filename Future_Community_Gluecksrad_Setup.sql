CREATE TABLE IF NOT EXISTS public.daily_wheel_spins (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  spin_date date NOT NULL,
  segment_index integer NOT NULL CHECK (segment_index BETWEEN 0 AND 5),
  reward_label text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS daily_wheel_spins_user_date_idx
  ON public.daily_wheel_spins(user_id, spin_date, created_at);
ALTER TABLE public.daily_wheel_spins ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Users can read their own wheel spins" ON public.daily_wheel_spins;
CREATE POLICY "Users can read their own wheel spins"
  ON public.daily_wheel_spins FOR SELECT TO authenticated
  USING (user_id = auth.uid());
GRANT SELECT ON public.daily_wheel_spins TO authenticated;

CREATE OR REPLACE FUNCTION public.get_daily_wheel_status()
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth
AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_day date := (now() AT TIME ZONE 'Europe/Berlin')::date;
  v_count integer;
  v_last text;
  v_remaining integer;
BEGIN
  IF v_uid IS NULL THEN RAISE EXCEPTION 'Bitte anmelden.'; END IF;
  SELECT count(*), (array_agg(reward_label ORDER BY created_at DESC))[1]
    INTO v_count, v_last
    FROM public.daily_wheel_spins
   WHERE user_id = v_uid AND spin_date = v_day;
  v_remaining := CASE WHEN v_count = 0 THEN 1
                      WHEN v_count = 1 AND v_last = 'Extra-Dreh' THEN 1
                      ELSE 0 END;
  RETURN jsonb_build_object('remaining_spins', v_remaining, 'spins_today', v_count);
END;
$$;

CREATE OR REPLACE FUNCTION public.spin_daily_wheel()
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth
AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_day date := (now() AT TIME ZONE 'Europe/Berlin')::date;
  v_count integer;
  v_last text;
  v_idx integer;
  v_label text;
  v_points integer := 0;
BEGIN
  IF v_uid IS NULL THEN RAISE EXCEPTION 'Bitte anmelden.'; END IF;
  -- Verhindert zwei gleichzeitige Drehungen desselben Accounts.
  PERFORM pg_advisory_xact_lock(hashtextextended(v_uid::text || v_day::text, 0));
  SELECT count(*), (array_agg(reward_label ORDER BY created_at DESC))[1]
    INTO v_count, v_last
    FROM public.daily_wheel_spins
   WHERE user_id = v_uid AND spin_date = v_day;
  IF NOT (v_count = 0 OR (v_count = 1 AND v_last = 'Extra-Dreh')) THEN
    RAISE EXCEPTION 'Du hast heute bereits alle verfügbaren Drehungen genutzt.';
  END IF;

  v_idx := floor(random() * 6)::integer;
  v_label := CASE v_idx
    WHEN 0 THEN '10 XP'
    WHEN 1 THEN '25 XP'
    WHEN 2 THEN '50 XP'
    WHEN 3 THEN '100 XP'
    WHEN 4 THEN 'Extra-Dreh'
    ELSE '25 XP'
  END;
  v_points := CASE v_idx WHEN 0 THEN 10 WHEN 1 THEN 25 WHEN 2 THEN 50 WHEN 3 THEN 100 WHEN 5 THEN 25 ELSE 0 END;

  IF v_points > 0 THEN
    UPDATE public.profiles SET points = COALESCE(points, 0) + v_points WHERE id = v_uid;
    IF NOT FOUND THEN RAISE EXCEPTION 'Profil nicht gefunden.'; END IF;
  END IF;

  INSERT INTO public.daily_wheel_spins(user_id, spin_date, segment_index, reward_label)
  VALUES (v_uid, v_day, v_idx, v_label);

  RETURN jsonb_build_object('segment_index', v_idx, 'reward_label', v_label,
                            'points_awarded', v_points);
END;
$$;

REVOKE ALL ON FUNCTION public.get_daily_wheel_status() FROM PUBLIC;
REVOKE ALL ON FUNCTION public.spin_daily_wheel() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.get_daily_wheel_status() TO authenticated;
GRANT EXECUTE ON FUNCTION public.spin_daily_wheel() TO authenticated;
